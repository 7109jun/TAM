/// 헤더 방식 할당자 공통부: 블록 앞 16바이트에 요청 크기를 적어 두므로 `realloc`이 옛 크기를 안다.
/// 대상이 `@raw_alloc(i64 total)`과 `@raw_free(ptr raw)`를 제공해야 한다.
const HEAP_HEADER: &str = "\
define ptr @tam_alloc(i64 %n) {
  %t = add i64 %n, 16
  %raw = call ptr @raw_alloc(i64 %t)
  %ok = icmp ne ptr %raw, null
  br i1 %ok, label %fine, label %oom
oom:
  call void @llvm.trap()
  unreachable
fine:
  store i64 %n, ptr %raw
  %p = getelementptr inbounds i8, ptr %raw, i64 16
  ret ptr %p
}

define void @tam_free(ptr %p) {
  %nul = icmp eq ptr %p, null
  br i1 %nul, label %done, label %go
go:
  %raw = getelementptr inbounds i8, ptr %p, i64 -16
  call void @raw_free(ptr %raw)
  br label %done
done:
  ret void
}

define ptr @tam_realloc(ptr %p, i64 %n) {
  %nul = icmp eq ptr %p, null
  br i1 %nul, label %fresh, label %grow
fresh:
  %a = call ptr @tam_alloc(i64 %n)
  ret ptr %a
grow:
  %hp = getelementptr inbounds i8, ptr %p, i64 -16
  %old = load i64, ptr %hp
  %q = call ptr @tam_alloc(i64 %n)
  %small = icmp ult i64 %old, %n
  %c = select i1 %small, i64 %old, i64 %n
  %r = call ptr @memcpy(ptr %q, ptr %p, i64 %c)
  call void @tam_free(ptr %p)
  ret ptr %q
}

";

/// 고정 영역 위의 할당자: 2의 거듭제곱 크기 등급별 해제 목록 + 범프. 해제된 블록은 같은 등급 요청에 재사용된다.
/// (영역을 되돌려 주거나 인접 블록을 합치지는 않는다. 블록은 최대 2배까지 낭비될 수 있다.)
fn bump_heap(base: u64, size: u64) -> String {
    format!(
        "\
@heap.cur = global i64 {base}
@heap.free = global [64 x ptr] zeroinitializer
@_fltused = global i32 0

declare i64 @llvm.ctlz.i64(i64, i1)

define i64 @size_class(i64 %total) {{
  %m = sub i64 %total, 1
  %lz = call i64 @llvm.ctlz.i64(i64 %m, i1 false)
  %c = sub i64 64, %lz
  %small = icmp ult i64 %c, 5
  %r = select i1 %small, i64 5, i64 %c
  ret i64 %r
}}

define ptr @raw_alloc(i64 %total) {{
  %c = call i64 @size_class(i64 %total)
  %slot = getelementptr inbounds [64 x ptr], ptr @heap.free, i64 0, i64 %c
  %head = load ptr, ptr %slot
  %has = icmp ne ptr %head, null
  br i1 %has, label %reuse, label %fresh
reuse:
  %next = load ptr, ptr %head
  store ptr %next, ptr %slot
  ret ptr %head
fresh:
  %cur = load i64, ptr @heap.cur
  %sz = shl i64 1, %c
  %new = add i64 %cur, %sz
  %over = icmp ugt i64 %new, {end}
  br i1 %over, label %fail, label %ok
fail:
  ret ptr null
ok:
  store i64 %new, ptr @heap.cur
  %p = inttoptr i64 %cur to ptr
  ret ptr %p
}}

define void @raw_free(ptr %raw) {{
  %n = load i64, ptr %raw
  %t = add i64 %n, 16
  %c = call i64 @size_class(i64 %t)
  %slot = getelementptr inbounds [64 x ptr], ptr @heap.free, i64 0, i64 %c
  %head = load ptr, ptr %slot
  store ptr %head, ptr %raw
  store ptr %raw, ptr %slot
  ret void
}}

",
        end = base + size
    )
}

