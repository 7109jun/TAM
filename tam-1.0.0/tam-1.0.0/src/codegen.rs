//! 타입 검사를 통과한 AST에서 텍스트 LLVM IR(.ll)을 생성한다.
//!
//! 모든 변수는 함수 entry 블록의 alloca로 두고 load/store로 접근한다(최적화는 LLVM 몫).
//! 정수 연산은 현재 wrapping이며 오버플로/0 나눗셈 trap은 아직 없다.

use std::collections::{BTreeSet, HashMap};
use std::collections::BTreeMap;

use crate::ast::*;
use crate::typeck::{needs_drop, Checked, Sigs, StructTable, Ty};
use crate::types::ll_quote;

type Val = (String, Ty);

/// 생성할 코드의 대상. 런타임(할당, 시작 코드)이 대상마다 다르다.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Target {
    /// 개발 호스트: libc가 있는 환경. 링크는 clang에 맡긴다.
    Host,
    /// Windows x64: CRT 없이 kernel32만 쓴다.
    Windows,
    /// x86-64 UEFI 응용(`BOOTX64.EFI`). 펌웨어의 boot services 위에서 돈다.
    Uefi,
    /// x86-64 레거시 BIOS 부팅 디스크 이미지. 부트 섹터가 롱 모드로 올려 준다.
    Bios,
    /// AArch64 베어메탈(QEMU `virt` 등): Linux Image 헤더로 시작하는 평평한 바이너리.
    Aarch64,
}

impl Target {
    /// 링크가 lld-link(PE/COFF)로 이뤄지는 대상.
    pub fn is_pe(self) -> bool {
        self != Target::Host
    }

    /// OS 없이 펌웨어/하드웨어 위에서 직접 도는 대상.
    pub fn is_firmware(self) -> bool {
        matches!(self, Target::Uefi | Target::Bios | Target::Aarch64)
    }

    pub fn triple(self) -> Option<&'static str> {
        match self {
            Target::Host => None,
            Target::Aarch64 => Some("aarch64-pc-windows-msvc"),
            _ => Some("x86_64-pc-windows-msvc"),
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Target::Host => "host",
            Target::Windows => "windows",
            Target::Uefi => "uefi",
            Target::Bios => "bios",
            Target::Aarch64 => "aarch64",
        }
    }
}

pub fn emit(p: &Program, ck: &Checked) -> String {
    emit_for(p, ck, Target::Host)
}

pub fn emit_for(p: &Program, ck: &Checked, target: Target) -> String {
    let sigs = &ck.sigs;
    let mut out = String::from("; generated by tamc\n");
    if let Some(t) = target.triple() {
        out.push_str(&format!("target triple = \"{t}\"\n"));
    }
    out.push('\n');
    for name in &ck.structs.order {
        let fields: Vec<String> = ck.structs.fields[name]
            .iter()
            .map(|(_, t)| t.llty())
            .collect();
        out.push_str(&format!("%{} = type {{ {} }}\n", ll_quote(name), fields.join(", ")));
    }
    if !ck.structs.order.is_empty() {
        out.push('\n');
    }
    let mut decls: BTreeSet<String> = BTreeSet::new();
    let mut funcs = String::new();
    let mut globals = String::new();
    let mut glue_queue: Vec<Ty> = Vec::new();
    // extern 함수: 호출 이름 -> 실제 심볼, 그리고 `declare`. 런타임이 이미 선언한 심볼은 다시 선언하지 않는다.
    let mut ext_syms: HashMap<String, String> = HashMap::new();
    let runtime_syms: &[&str] = match target {
        Target::Host => &["malloc", "realloc", "free"],
        Target::Windows => &["GetProcessHeap", "HeapAlloc", "HeapReAlloc", "HeapFree", "ExitProcess"],
        _ => &[],
    };
    for f in p.funcs.iter().filter(|f| f.ext.is_some()) {
        let sym = f.link.clone().unwrap_or_else(|| f.name.clone());
        ext_syms.insert(f.name.clone(), sym.clone());
        let (ptys, ret) = &sigs[&f.name];
        if !runtime_syms.contains(&sym.as_str()) {
            let params: Vec<String> = ptys.iter().map(|t| format!("{}{}", t.llty(), abi_attr(*t))).collect();
            let r = if *ret == Ty::Unit { "void".to_string() } else { format!("{}{}", abi_attr_prefix(*ret), ret.llty()) };
            decls.insert(format!("declare {r} @{}({})", ll_quote(&sym), params.join(", ")));
        }
    }
    for (fi, f) in p.funcs.iter().enumerate() {
        if f.ext.is_some() {
            continue;
        }
        let mut cg = Cg {
            ext_syms: &ext_syms,
            sigs,
            structs: &ck.structs,
            body: String::new(),
            allocas: String::new(),
            tmp: 0,
            lbl: 0,
            cur: "entry".to_string(),
            scopes: Vec::new(),
            loops: Vec::new(),
            ret: sigs[&f.name].1,
            decls: BTreeSet::new(),
            fi,
            strs: String::new(),
            nstr: 0,
            drops: Vec::new(),
            flag_of: HashMap::new(),
            glue_tys: Vec::new(),
            target,
        };
        let text = cg.func(f);
        // 지역 변수를 레지스터로 올린다. (`TAMC_NO_OPT=1`이면 끈다: 디버깅용)
        funcs.push_str(&crate::opt::promote(&text));
        funcs.push('\n');
        decls.append(&mut cg.decls);
        globals.push_str(&cg.strs);
        glue_queue.append(&mut cg.glue_tys);
    }
    // drop glue: 필요한 타입마다 해제 함수를 만든다 (필드 속 타입은 연쇄적으로 추가된다).
    let mut glue: BTreeMap<String, String> = BTreeMap::new();
    while let Some(ty) = glue_queue.pop() {
        let name = drop_name(ty);
        if glue.contains_key(&name) {
            continue;
        }
        let body = gen_glue(ty, &name, &ck.structs, &mut glue_queue);
        glue.insert(name, body);
    }
    for g in glue.values() {
        funcs.push_str(g);
        funcs.push('\n');
    }
    decls.insert("declare void @llvm.trap()".to_string());
    for d in &decls {
        out.push_str(d);
        out.push('\n');
    }
    if !decls.is_empty() {
        out.push('\n');
    }
    if !globals.is_empty() {
        out.push_str(&globals);
        out.push('\n');
    }
    out.push_str(&runtime(target));
    out.push_str(&funcs);
    if target.is_pe() {
        // 4KiB를 넘는 스택 프레임은 `__chkstk`를 부른다. CRT가 없으니 직접 제공한다.
        out.push_str(chkstk_asm(target));
        out.push_str("attributes #1 = { nounwind }\n");
    }
    out
}

/// PE 대상용 `__chkstk`: 큰 프레임이 가드 페이지를 한 쪽씩 밟도록 스택을 미리 건드린다.
fn chkstk_asm(target: Target) -> &'static str {
    if target == Target::Aarch64 {
        "module asm \".globl __chkstk\"
module asm \"__chkstk:\"
module asm \"  lsl x16, x15, #4\"
module asm \"  mov x17, sp\"
module asm \"1:\"
module asm \"  sub x17, x17, #4096\"
module asm \"  subs x16, x16, #4096\"
module asm \"  ldr xzr, [x17]\"
module asm \"  b.gt 1b\"
module asm \"  ret\"
"
    } else {
        "module asm \".globl __chkstk\"
module asm \"__chkstk:\"
module asm \"  pushq %rcx\"
module asm \"  pushq %rax\"
module asm \"  cmpq $0x1000, %rax\"
module asm \"  leaq 24(%rsp), %rcx\"
module asm \"  jb 2f\"
module asm \"1:\"
module asm \"  subq $0x1000, %rcx\"
module asm \"  testq %rcx, (%rcx)\"
module asm \"  subq $0x1000, %rax\"
module asm \"  cmpq $0x1000, %rax\"
module asm \"  ja 1b\"
module asm \"2:\"
module asm \"  subq %rax, %rcx\"
module asm \"  testq %rcx, (%rcx)\"
module asm \"  popq %rax\"
module asm \"  popq %rcx\"
module asm \"  ret\"
"
    }
}

/// 프로그램의 `extern` 함수가 가져오는 DLL별 함수 이름. (Windows 대상의 import lib 생성에 쓴다.)
/// 대상에 맞지 않는 extern(Windows에서 `\"c\"`, 호스트에서 DLL)은 오류다.
pub fn extern_imports(p: &Program, target: Target) -> Result<std::collections::BTreeMap<String, BTreeSet<String>>, crate::diag::Diag> {
    let mut map: std::collections::BTreeMap<String, BTreeSet<String>> = std::collections::BTreeMap::new();
    for f in p.funcs.iter().filter(|f| f.ext.is_some()) {
        let lib = f.ext.as_deref().unwrap();
        match (target, lib) {
            (Target::Host, "c") => {}
            (Target::Host, _) => {
                return Err(crate::diag::Diag::new(
                    format!("`extern \"{lib}\"` is only available when targeting Windows"),
                    f.span,
                    "build with `--target windows`, or use `extern \"c\"` for libc",
                ))
            }
            (Target::Windows, "c") => {
                return Err(crate::diag::Diag::new(
                    "`extern \"c\"` is not available when targeting Windows (there is no C runtime)",
                    f.span,
                    "import from a DLL instead, e.g. `extern \"kernel32\"`",
                ))
            }
            (t @ (Target::Uefi | Target::Bios | Target::Aarch64), _) => {
                return Err(crate::diag::Diag::new(
                    format!("`extern` is not available when targeting {} (there is no OS or library to link)", t.name()),
                    f.span,
                    "use the hardware built-ins (`mmio_read32`, `port_out8`, ...) instead",
                ))
            }
            (Target::Windows, dll) => {
                let dll = if dll.to_ascii_lowercase().ends_with(".dll") { dll.to_string() } else { format!("{dll}.dll") };
                map.entry(dll).or_default().insert(f.link.clone().unwrap_or_else(|| f.name.clone()));
            }
        }
    }
    Ok(map)
}

/// 대상별 런타임. 컴파일러가 만든 코드는 `tam_alloc`/`tam_realloc`/`tam_free`만 부른다.
/// (교체 가능한 전역 allocator는 이 세 함수를 바꾸는 방식으로 붙인다.)
fn runtime(target: Target) -> String {
    match target {
        Target::Host => "\
declare ptr @malloc(i64)
declare ptr @realloc(ptr, i64)
declare void @free(ptr)

define ptr @tam_alloc(i64 %n) {
  %p = call ptr @malloc(i64 %n)
  ret ptr %p
}

define ptr @tam_realloc(ptr %p, i64 %n) {
  %q = call ptr @realloc(ptr %p, i64 %n)
  ret ptr %q
}

define void @tam_free(ptr %p) {
  call void @free(ptr %p)
  ret void
}

"
        .to_string(),
        Target::Windows => [WINDOWS_HEAP, MEM_FUNCS, WINDOWS_ENTRY].concat(),
        Target::Uefi => [UEFI_RT, HEAP_HEADER, MEM_FUNCS].concat(),
        Target::Bios => [bump_heap(0x200000, 0x2000000), HEAP_HEADER.to_string(), MEM_FUNCS.to_string(), BIOS_ENTRY.to_string()].concat(),
        Target::Aarch64 => [bump_heap(0x44000000, 0x2000000), HEAP_HEADER.to_string(), MEM_FUNCS.to_string(), AARCH64_ENTRY.to_string()].concat(),
    }
}

const WINDOWS_HEAP: &str = "\
declare ptr @GetProcessHeap()
declare ptr @HeapAlloc(ptr, i32, i64)
declare ptr @HeapReAlloc(ptr, i32, ptr, i64)
declare i32 @HeapFree(ptr, i32, ptr)
declare void @ExitProcess(i32)

@_fltused = global i32 0

define ptr @tam_alloc(i64 %n) {
  %h = call ptr @GetProcessHeap()
  %p = call ptr @HeapAlloc(ptr %h, i32 0, i64 %n)
  ret ptr %p
}

define ptr @tam_realloc(ptr %p, i64 %n) {
  %h = call ptr @GetProcessHeap()
  %q = call ptr @HeapReAlloc(ptr %h, i32 0, ptr %p, i64 %n)
  ret ptr %q
}

define void @tam_free(ptr %p) {
  %h = call ptr @GetProcessHeap()
  %r = call i32 @HeapFree(ptr %h, i32 0, ptr %p)
  ret void
}

";

/// CRT가 없는 대상용 `memcpy`/`memset`/`memmove`와 속성 정의.
const MEM_FUNCS: &str = "\
; CRT가 없으므로 LLVM이 만들어 내는 memcpy/memset/memmove 호출을 직접 제공한다.
; no-builtins: 이 루프가 다시 memcpy 호출로 바뀌는 것을 막는다.
define ptr @memcpy(ptr %d, ptr %s, i64 %n) #0 {
entry:
  br label %loop
loop:
  %i = phi i64 [ 0, %entry ], [ %i1, %body ]
  %done = icmp eq i64 %i, %n
  br i1 %done, label %exit, label %body
body:
  %sp = getelementptr inbounds i8, ptr %s, i64 %i
  %dp = getelementptr inbounds i8, ptr %d, i64 %i
  %b = load i8, ptr %sp
  store i8 %b, ptr %dp
  %i1 = add i64 %i, 1
  br label %loop
exit:
  ret ptr %d
}

define ptr @memset(ptr %d, i32 %c, i64 %n) #0 {
entry:
  %b = trunc i32 %c to i8
  br label %loop
loop:
  %i = phi i64 [ 0, %entry ], [ %i1, %body ]
  %done = icmp eq i64 %i, %n
  br i1 %done, label %exit, label %body
body:
  %dp = getelementptr inbounds i8, ptr %d, i64 %i
  store i8 %b, ptr %dp
  %i1 = add i64 %i, 1
  br label %loop
exit:
  ret ptr %d
}

define ptr @memmove(ptr %d, ptr %s, i64 %n) #0 {
entry:
  %back = icmp ugt ptr %d, %s
  br i1 %back, label %bloop, label %floop
floop:
  %i = phi i64 [ 0, %entry ], [ %i1, %fbody ]
  %fdone = icmp eq i64 %i, %n
  br i1 %fdone, label %exit, label %fbody
fbody:
  %fsp = getelementptr inbounds i8, ptr %s, i64 %i
  %fdp = getelementptr inbounds i8, ptr %d, i64 %i
  %fb = load i8, ptr %fsp
  store i8 %fb, ptr %fdp
  %i1 = add i64 %i, 1
  br label %floop
bloop:
  %j = phi i64 [ %n, %entry ], [ %j1, %bbody ]
  %bdone = icmp eq i64 %j, 0
  br i1 %bdone, label %exit, label %bbody
bbody:
  %j1 = sub i64 %j, 1
  %bsp = getelementptr inbounds i8, ptr %s, i64 %j1
  %bdp = getelementptr inbounds i8, ptr %d, i64 %j1
  %bb = load i8, ptr %bsp
  store i8 %bb, ptr %bdp
  br label %bloop
exit:
  ret ptr %d
}

attributes #0 = { noinline nounwind \"no-builtins\" }

";

const WINDOWS_ENTRY: &str = "\
; 프로세스 진입점: `main`을 부르고 그 값으로 종료한다.
define void @mainCRTStartup() #1 {
  %c = call i32 @main()
  call void @ExitProcess(i32 %c)
  unreachable
}

";


struct Cg<'a> {
    ext_syms: &'a HashMap<String, String>,
    sigs: &'a Sigs,
    structs: &'a StructTable,
    body: String,
    allocas: String,
    tmp: u32,
    lbl: u32,
    cur: String,
    scopes: Vec<HashMap<String, (String, Ty)>>,
    ret: Ty,
    decls: BTreeSet<String>,
    /// 함수 번호. 문자열 전역 이름을 함수 간에 겹치지 않게 한다.
    fi: usize,
    strs: String,
    nstr: u32,
    /// 스코프별 해제 대상 (선언 순서). `scopes`와 같이 push/pop 된다.
    drops: Vec<Vec<DropEnt>>,
    /// 바깥쪽부터 (continue 라벨, break 라벨, 루프 진입 시 스코프 깊이)
    loops: Vec<(String, String, usize)>,
    /// 변수 alloca -> 그 변수의 "값이 살아 있음" 플래그 alloca
    flag_of: HashMap<String, String>,
    glue_tys: Vec<Ty>,
    target: Target,
}

struct DropEnt {
    ptr: String,
    flag: String,
    ty: Ty,
}

/// C ABI에서 작은 정수 인자/반환은 호출하는 쪽이 32비트로 확장했다고 가정한다. 그 표시.
fn abi_attr(t: Ty) -> &'static str {
    match t {
        Ty::Bool | Ty::U8 | Ty::U16 => " zeroext",
        Ty::I8 | Ty::I16 => " signext",
        _ => "",
    }
}

fn abi_attr_prefix(t: Ty) -> &'static str {
    match t {
        Ty::Bool | Ty::U8 | Ty::U16 => "zeroext ",
        Ty::I8 | Ty::I16 => "signext ",
        _ => "",
    }
}

fn is_builtin(name: &str) -> bool {
    crate::typeck::builtins().iter().any(|b| b.0 == name)
}

fn drop_name(ty: Ty) -> String {
    format!("@{}", ll_quote(&format!("drop.{}", ty.name())))
}

/// `ty` 값을 해제하는 `void @drop.T(ptr)` 함수 본문.
fn gen_glue(ty: Ty, name: &str, st: &StructTable, queue: &mut Vec<Ty>) -> String {
    let mut b = format!("define void {name}(ptr %p) {{\nentry:\n");
    match ty {
        Ty::String => {
            b.push_str("  %pp = getelementptr inbounds { ptr, i64, i64 }, ptr %p, i32 0, i32 0\n  %buf = load ptr, ptr %pp\n  call void @tam_free(ptr %buf)\n");
        }
        Ty::Struct(n) => {
            for (i, (_, ft)) in st.fields[n].iter().enumerate() {
                if needs_drop(*ft, st) {
                    queue.push(*ft);
                    b.push_str(&format!(
                        "  %f{i} = getelementptr inbounds %{}, ptr %p, i32 0, i32 {i}\n  call void {}(ptr %f{i})\n",
                        ll_quote(n),
                        drop_name(*ft)
                    ));
                }
            }
        }
        Ty::Result(t, e) => {
            let rl = ty.llty();
            b.push_str(&format!(
                "  %tp = getelementptr inbounds {rl}, ptr %p, i32 0, i32 0\n  %tag = load i1, ptr %tp\n  br i1 %tag, label %ok, label %err\n"
            ));
            for (lbl, pt, idx) in [("ok", *t, 1), ("err", *e, 2)] {
                b.push_str(&format!("{lbl}:\n"));
                if needs_drop(pt, st) {
                    queue.push(pt);
                    b.push_str(&format!(
                        "  %{lbl}p = getelementptr inbounds {rl}, ptr %p, i32 0, i32 {idx}\n  call void {}(ptr %{lbl}p)\n",
                        drop_name(pt)
                    ));
                }
                b.push_str("  ret void\n");
            }
            b.push_str("}\n");
            return b;
        }
        _ => {}
    }
    b.push_str("  ret void\n}\n");
    b
}

/// LLVM `c"..."` 상수 본문. 출력 가능한 ASCII 외에는 `\XX`로 쓴다.
fn ll_bytes(s: &str) -> String {
    let mut out = String::new();
    for b in s.bytes() {
        if (0x20..0x7f).contains(&b) && b != b'"' && b != b'\\' {
            out.push(b as char);
        } else {
            out.push_str(&format!("\\{b:02X}"));
        }
    }
    out
}

impl<'a> Cg<'a> {
    fn t(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }

    fn line(&mut self, s: &str) {
        self.body.push_str("  ");
        self.body.push_str(s);
        self.body.push('\n');
    }

    fn new_label(&mut self, hint: &str) -> String {
        self.lbl += 1;
        format!("{hint}{}", self.lbl)
    }

    fn start(&mut self, label: &str) {
        self.body.push_str(label);
        self.body.push_str(":\n");
        self.cur = label.to_string();
    }

    fn lookup(&self, name: &str) -> (String, Ty) {
        self.scopes
            .iter()
            .rev()
            .find_map(|s| s.get(name))
            .cloned()
            .expect("typeck guarantees variables exist")
    }

    fn declare(&mut self, name: &str, ty: Ty) -> String {
        self.tmp += 1;
        let ptr = format!("%{}.{}", name, self.tmp);
        self.allocas
            .push_str(&format!("  {ptr} = alloca {}\n", ty.llty()));
        self.scopes
            .last_mut()
            .unwrap()
            .insert(name.to_string(), (ptr.clone(), ty));
        if needs_drop(ty, self.structs) {
            let flag = format!("{ptr}.live");
            self.allocas.push_str(&format!("  {flag} = alloca i1\n  store i1 false, ptr {flag}\n"));
            self.flag_of.insert(ptr.clone(), flag.clone());
            self.drops.last_mut().unwrap().push(DropEnt {
                ptr: ptr.clone(),
                flag,
                ty,
            });
        }
        ptr
    }

    fn push_scope(&mut self) {
        self.scopes.push(HashMap::new());
        self.drops.push(Vec::new());
    }

    fn pop_scope(&mut self) {
        self.scopes.pop();
        self.drops.pop();
    }

    /// 변수의 "값이 살아 있음" 플래그를 바꾼다. (해제 대상이 아니면 아무 일도 안 한다.)
    fn set_live(&mut self, ptr: &str, live: bool) {
        if let Some(flag) = self.flag_of.get(ptr).cloned() {
            self.line(&format!("store i1 {live}, ptr {flag}"));
        }
    }

    fn call_drop(&mut self, ptr: &str, ty: Ty) {
        self.glue_tys.push(ty);
        self.line(&format!("call void {}(ptr {ptr})", drop_name(ty)));
    }

    /// 플래그가 켜져 있으면 해제하고 끈다.
    fn drop_if_live(&mut self, ptr: &str, flag: &str, ty: Ty) {
        let f = self.t();
        self.line(&format!("{f} = load i1, ptr {flag}"));
        let (ld, ls) = (self.new_label("drop.do"), self.new_label("drop.skip"));
        self.line(&format!("br i1 {f}, label %{ld}, label %{ls}"));
        self.start(&ld);
        self.call_drop(ptr, ty);
        self.line(&format!("store i1 false, ptr {flag}"));
        self.line(&format!("br label %{ls}"));
        self.start(&ls);
    }

    /// 가장 안쪽 스코프의 변수들을 선언 역순으로 해제한다.
    fn end_scope_drops(&mut self) {
        let ents: Vec<(String, String, Ty)> = self
            .drops
            .last()
            .map(|v| v.iter().rev().map(|d| (d.ptr.clone(), d.flag.clone(), d.ty)).collect())
            .unwrap_or_default();
        for (p, f, t) in ents {
            self.drop_if_live(&p, &f, t);
        }
    }

    /// `break`/`continue`용: 루프 안쪽에서 선언된 스코프(깊이 `depth` 이상)만 해제한다.
    fn drop_scopes_from(&mut self, depth: usize) {
        let ents: Vec<(String, String, Ty)> = self
            .drops
            .iter()
            .skip(depth)
            .rev()
            .flat_map(|v| v.iter().rev().map(|d| (d.ptr.clone(), d.flag.clone(), d.ty)))
            .collect();
        for (p, f, t) in ents {
            self.drop_if_live(&p, &f, t);
        }
    }

    /// `return`/`?`용: 함수의 모든 스코프를 안쪽부터 해제한다.
    fn drop_all_scopes(&mut self) {
        let ents: Vec<(String, String, Ty)> = self
            .drops
            .iter()
            .rev()
            .flat_map(|v| v.iter().rev().map(|d| (d.ptr.clone(), d.flag.clone(), d.ty)))
            .collect();
        for (p, f, t) in ents {
            self.drop_if_live(&p, &f, t);
        }
    }

    fn func(&mut self, f: &Func) -> String {
        self.push_scope();
        let (ptys, _) = self.sigs[&f.name].clone();
        let mut header_params = Vec::new();
        for (p, ty) in f.params.iter().zip(&ptys) {
            header_params.push(format!("{} %{}.arg", (*ty).llty(), p.name));
            let ptr = self.declare(&p.name, *ty);
            self.line(&format!("store {} %{}.arg, ptr {ptr}", (*ty).llty(), p.name));
            self.set_live(&ptr, true);
        }
        let val = self.block(&f.body);
        self.end_scope_drops();
        match self.ret {
            Ty::Unit => self.line("ret void"),
            ty => match val {
                Some((v, _)) => self.line(&format!("ret {} {v}", ty.llty())),
                None => self.line("unreachable"),
            },
        }
        self.pop_scope();
        format!(
            "define {} @{}({}){} {{\nentry:\n{}{}}}\n",
            self.ret.llty(),
            ll_quote(&f.name),
            header_params.join(", "),
            if self.target.is_pe() { " #1" } else { "" },
            self.allocas,
            self.body
        )
    }

    /// 내장 함수를 IR로 풀어 쓴다. 할당은 런타임의
    /// `tam_alloc`/`tam_realloc`/`tam_free`를 거친다.
    fn builtin(&mut self, name: &str, args: &[Expr]) -> Option<Val> {
        const S: &str = "{ ptr, i64, i64 }";
        match name {
            "string_from" => {
                let (sv, _) = self.expr(&args[0])?;
                let (src, n) = (self.t(), self.t());
                self.line(&format!("{src} = extractvalue {{ ptr, i64 }} {sv}, 0"));
                self.line(&format!("{n} = extractvalue {{ ptr, i64 }} {sv}, 1"));
                let (z, cap, m) = (self.t(), self.t(), self.t());
                self.line(&format!("{z} = icmp eq i64 {n}, 0"));
                self.line(&format!("{cap} = select i1 {z}, i64 1, i64 {n}"));
                self.line(&format!("{m} = call ptr @tam_alloc(i64 {cap})"));
                self.line(&format!("call void @llvm.memcpy.p0.p0.i64(ptr {m}, ptr {src}, i64 {n}, i1 false)"));
                self.decls.insert("declare void @llvm.memcpy.p0.p0.i64(ptr, ptr, i64, i1)".to_string());
                let (a, b, c) = (self.t(), self.t(), self.t());
                self.line(&format!("{a} = insertvalue {S} undef, ptr {m}, 0"));
                self.line(&format!("{b} = insertvalue {S} {a}, i64 {n}, 1"));
                self.line(&format!("{c} = insertvalue {S} {b}, i64 {cap}, 2"));
                Some((c, Ty::String))
            }
            "string_push" => {
                let (r, _) = self.expr(&args[0])?;
                let (byte, _) = self.expr(&args[1])?;
                let (lenp, capp, bufp) = (self.t(), self.t(), self.t());
                self.line(&format!("{lenp} = getelementptr inbounds {S}, ptr {r}, i32 0, i32 1"));
                self.line(&format!("{capp} = getelementptr inbounds {S}, ptr {r}, i32 0, i32 2"));
                self.line(&format!("{bufp} = getelementptr inbounds {S}, ptr {r}, i32 0, i32 0"));
                let (len, cap, full) = (self.t(), self.t(), self.t());
                self.line(&format!("{len} = load i64, ptr {lenp}"));
                self.line(&format!("{cap} = load i64, ptr {capp}"));
                self.line(&format!("{full} = icmp eq i64 {len}, {cap}"));
                let (lg, lc) = (self.new_label("push.grow"), self.new_label("push.store"));
                self.line(&format!("br i1 {full}, label %{lg}, label %{lc}"));
                self.start(&lg);
                let (nc, old, np) = (self.t(), self.t(), self.t());
                self.line(&format!("{nc} = mul i64 {cap}, 2"));
                self.line(&format!("{old} = load ptr, ptr {bufp}"));
                self.line(&format!("{np} = call ptr @tam_realloc(ptr {old}, i64 {nc})"));
                self.line(&format!("store ptr {np}, ptr {bufp}"));
                self.line(&format!("store i64 {nc}, ptr {capp}"));
                self.line(&format!("br label %{lc}"));
                self.start(&lc);
                let (buf, slot, nl) = (self.t(), self.t(), self.t());
                self.line(&format!("{buf} = load ptr, ptr {bufp}"));
                self.line(&format!("{slot} = getelementptr inbounds i8, ptr {buf}, i64 {len}"));
                self.line(&format!("store i8 {byte}, ptr {slot}"));
                self.line(&format!("{nl} = add i64 {len}, 1"));
                self.line(&format!("store i64 {nl}, ptr {lenp}"));
                None
            }
            "as_str" => {
                let (r, _) = self.expr(&args[0])?;
                let (pp, lp, p, l) = (self.t(), self.t(), self.t(), self.t());
                self.line(&format!("{pp} = getelementptr inbounds {S}, ptr {r}, i32 0, i32 0"));
                self.line(&format!("{lp} = getelementptr inbounds {S}, ptr {r}, i32 0, i32 1"));
                self.line(&format!("{p} = load ptr, ptr {pp}"));
                self.line(&format!("{l} = load i64, ptr {lp}"));
                let (a, b) = (self.t(), self.t());
                self.line(&format!("{a} = insertvalue {{ ptr, i64 }} undef, ptr {p}, 0"));
                self.line(&format!("{b} = insertvalue {{ ptr, i64 }} {a}, i64 {l}, 1"));
                Some((b, Ty::Str))
            }
            "alloc" => {
                let (n, _) = self.expr(&args[0])?;
                let t = self.t();
                self.line(&format!("{t} = call ptr @tam_alloc(i64 {n})"));
                Some((t, Ty::ptr(Ty::U8, true)))
            }
            "free" => {
                let (p, _) = self.expr(&args[0])?;
                self.line(&format!("call void @tam_free(ptr {p})"));
                None
            }
            "mmio_read8" | "mmio_read16" | "mmio_read32" | "mmio_read64" => {
                let bits: u32 = name["mmio_read".len()..].parse().unwrap();
                let (a, _) = self.expr(&args[0])?;
                let (p, v) = (self.t(), self.t());
                self.line(&format!("{p} = inttoptr i64 {a} to ptr"));
                self.line(&format!("{v} = load volatile i{bits}, ptr {p}, align {}", bits / 8));
                let ty = match bits { 8 => Ty::U8, 16 => Ty::U16, 32 => Ty::U32, _ => Ty::U64 };
                Some((v, ty))
            }
            "mmio_write8" | "mmio_write16" | "mmio_write32" | "mmio_write64" => {
                let bits: u32 = name["mmio_write".len()..].parse().unwrap();
                let (a, _) = self.expr(&args[0])?;
                let (v, _) = self.expr(&args[1])?;
                let p = self.t();
                self.line(&format!("{p} = inttoptr i64 {a} to ptr"));
                self.line(&format!("store volatile i{bits} {v}, ptr {p}, align {}", bits / 8));
                None
            }
            "port_in8" | "port_in32" => {
                let (port, _) = self.expr(&args[0])?;
                let v = self.t();
                if name == "port_in8" {
                    self.line(&format!("{v} = call i8 asm sideeffect \"inb %dx, %al\", \"={{al}},{{dx}},~{{memory}}\"(i16 {port})"));
                    Some((v, Ty::U8))
                } else {
                    self.line(&format!("{v} = call i32 asm sideeffect \"inl %dx, %eax\", \"={{ax}},{{dx}},~{{memory}}\"(i16 {port})"));
                    Some((v, Ty::U32))
                }
            }
            "port_out8" | "port_out32" => {
                let (port, _) = self.expr(&args[0])?;
                let (v, _) = self.expr(&args[1])?;
                if name == "port_out8" {
                    self.line(&format!("call void asm sideeffect \"outb %al, %dx\", \"{{al}},{{dx}},~{{memory}}\"(i8 {v}, i16 {port})"));
                } else {
                    self.line(&format!("call void asm sideeffect \"outl %eax, %dx\", \"{{ax}},{{dx}},~{{memory}}\"(i32 {v}, i16 {port})"));
                }
                None
            }
            "panic" => {
                let (sv, _) = self.expr(&args[0])?;
                if self.target == Target::Host {
                    self.decls.insert(panic_def());
                    let (p, n) = (self.t(), self.t());
                    self.line(&format!("{p} = extractvalue {{ ptr, i64 }} {sv}, 0"));
                    self.line(&format!("{n} = extractvalue {{ ptr, i64 }} {sv}, 1"));
                    self.line(&format!("call void @tam_panic(ptr {p}, i64 {n})"));
                } else {
                    self.line("call void @llvm.trap()");
                }
                self.line("unreachable");
                let dead = self.new_label("dead");
                self.start(&dead);
                None
            }
            "assert" => {
                let (c, _) = self.expr(&args[0])?;
                let bad = self.t();
                self.line(&format!("{bad} = xor i1 {c}, true"));
                self.trap_if(&bad, "assertion failed");
                None
            }
            "halt" => {
                let asm = if self.target == Target::Aarch64 { "wfi" } else { "hlt" };
                self.line(&format!("call void asm sideeffect \"{asm}\", \"~{{memory}}\"()"));
                None
            }
            "semihost" => {
                let (op, _) = self.expr(&args[0])?;
                let (arg, _) = self.expr(&args[1])?;
                let r = self.t();
                self.line(&format!("{r} = call i64 asm sideeffect \"hlt #0xf000\", \"={{x0}},{{x0}},{{x1}},~{{memory}}\"(i64 {op}, i64 {arg})"));
                Some((r, Ty::U64))
            }
            "ccall0" | "ccall1" | "ccall2" | "ccall3" | "ccall4" => {
                let (f, _) = self.expr(&args[0])?;
                let mut vals = Vec::new();
                for a in &args[1..] {
                    let (v, _) = self.expr(a)?;
                    vals.push(format!("i64 {v}"));
                }
                let r = self.t();
                self.line(&format!("{r} = call i64 {f}({})", vals.join(", ")));
                Some((r, Ty::U64))
            }
            "efi_system_table" | "efi_image_handle" => {
                let g = if name == "efi_system_table" { "@efi.systab" } else { "@efi.image" };
                let v = self.t();
                self.line(&format!("{v} = load ptr, ptr {g}"));
                Some((v, Ty::ptr(Ty::U8, true)))
            }
            _ => unreachable!("not a builtin"),
        }
    }

    fn field_index(&self, sname: &str, field: &str) -> usize {
        self.structs.fields[sname]
            .iter()
            .position(|(n, _)| n == field)
            .expect("typeck guarantees the field exists")
    }

    /// 값을 임시 alloca에 담아 주소를 돌려준다. (rvalue 구조체의 필드를 읽을 때 쓴다.)
    fn spill(&mut self, e: &Expr) -> Option<String> {
        let (v, ty) = self.expr(e)?;
        self.tmp += 1;
        let ptr = format!("%spill.{}", self.tmp);
        self.allocas
            .push_str(&format!("  {ptr} = alloca {}\n", ty.llty()));
        self.line(&format!("store {} {v}, ptr {ptr}", ty.llty()));
        Some(ptr)
    }

    /// 정수 값을 i64로 넓힌다.
    fn widen(&mut self, v: String, ty: Ty) -> String {
        if ty.bits() < 64 {
            let w = self.t();
            let inst = if ty.is_signed() { "sext" } else { "zext" };
            self.line(&format!("{w} = {inst} {} {v} to i64", ty.llty()));
            w
        } else {
            v
        }
    }

    /// 조건이 참이면 trap한다.
    fn trap_if(&mut self, bad: &str, msg: &str) {
        let (ok, fail) = (self.new_label("trap.ok"), self.new_label("trap.fail"));
        self.line(&format!("br i1 {bad}, label %{fail}, label %{ok}"));
        self.start(&fail);
        self.panic_with(msg);
        self.start(&ok);
    }

    /// 정적 문자열 전역을 만들고 `(전역 이름, 길이)`를 돌려준다.
    fn static_bytes(&mut self, s: &str) -> (String, usize) {
        let g = format!("@.str.{}.{}", self.fi, self.nstr);
        self.nstr += 1;
        self.strs.push_str(&format!(
            "{g} = private unnamed_addr constant [{} x i8] c\"{}\"\n",
            s.len(),
            ll_bytes(s)
        ));
        (g, s.len())
    }

    /// 메시지를 (호스트에서는 stderr에) 찍고 trap한다. 블록을 `unreachable`로 끝낸다.
    fn panic_with(&mut self, msg: &str) {
        if self.target == Target::Host {
            self.decls.insert(panic_def());
            let (g, n) = self.static_bytes(msg);
            self.line(&format!("call void @tam_panic(ptr {g}, i64 {n})"));
        } else {
            self.line("call void @llvm.trap()");
        }
        self.line("unreachable");
    }

    /// 오버플로를 검사하는 정수 연산(`add`/`sub`/`mul`). 넘치면 trap한다.
    fn checked_arith(&mut self, op: &str, ty: Ty, a: &str, b: &str) -> String {
        let ll = ty.llty();
        let kind = if ty.is_signed() { "s" } else { "u" };
        let name = format!("llvm.{kind}{op}.with.overflow.{ll}");
        self.decls.insert(format!("declare {{ {ll}, i1 }} @{name}({ll}, {ll})"));
        let (r, v, o) = (self.t(), self.t(), self.t());
        self.line(&format!("{r} = call {{ {ll}, i1 }} @{name}({ll} {a}, {ll} {b})"));
        self.line(&format!("{v} = extractvalue {{ {ll}, i1 }} {r}, 0"));
        self.line(&format!("{o} = extractvalue {{ {ll}, i1 }} {r}, 1"));
        self.trap_if(&o, "integer overflow");
        v
    }

    /// 배열/`&[T; N]`/`&[T]`의 (첫 원소 주소, 길이(i64), 원소 타입).
    fn seq_parts(&mut self, base: &Expr) -> Option<(String, String, Ty)> {
        match base.ty {
            Ty::Array(elem, n) => {
                let p = if base.is_place() { self.place(base)?.0 } else { self.spill(base)? };
                Some((p, n.to_string(), *elem))
            }
            Ty::Ref(Ty::Array(elem, n), _) => Some((self.expr(base)?.0, n.to_string(), **elem)),
            Ty::Ref(Ty::Slice(elem), _) => {
                let (fat, _) = self.expr(base)?;
                let (p, l) = (self.t(), self.t());
                self.line(&format!("{p} = extractvalue {{ ptr, i64 }} {fat}, 0"));
                self.line(&format!("{l} = extractvalue {{ ptr, i64 }} {fat}, 1"));
                Some((p, l, **elem))
            }
            _ => None,
        }
    }

    /// 조건이 거짓이면 trap한다. (배열/슬라이스 경계 검사)
    fn bounds_check(&mut self, ok: &str) {
        let (good, bad) = (self.new_label("bounds.ok"), self.new_label("bounds.fail"));
        self.line(&format!("br i1 {ok}, label %{good}, label %{bad}"));
        self.start(&bad);
        self.panic_with("index out of bounds");
        self.start(&good);
    }

    /// 배열 리터럴/반복 식을 `dest` 주소에 직접 만든다. (큰 배열을 값으로 만들지 않으려고)
    fn init_array(&mut self, dest: &str, e: &Expr) -> Option<()> {
        let Ty::Array(elem, n) = e.ty else { unreachable!("not an array expression") };
        let at = e.ty.llty();
        match &e.kind {
            ExprKind::Array(xs) => {
                for (i, x) in xs.iter().enumerate() {
                    let slot = self.t();
                    self.line(&format!("{slot} = getelementptr inbounds {at}, ptr {dest}, i64 0, i64 {i}"));
                    if matches!(x.kind, ExprKind::Array(_) | ExprKind::Repeat(..)) {
                        self.init_array(&slot, x)?;
                    } else {
                        let (v, t) = self.expr(x)?;
                        self.line(&format!("store {} {v}, ptr {slot}", t.llty()));
                    }
                }
            }
            ExprKind::Repeat(x, _) => {
                let zero = matches!(x.kind, ExprKind::Int(0) | ExprKind::Bool(false)) && elem.is_int() || matches!(x.kind, ExprKind::Bool(false));
                if zero {
                    self.line(&format!(
                        "call void @llvm.memset.p0.i64(ptr {dest}, i8 0, i64 ptrtoint (ptr getelementptr ({at}, ptr null, i32 1) to i64), i1 false)"
                    ));
                    self.decls.insert("declare void @llvm.memset.p0.i64(ptr, i8, i64, i1)".to_string());
                    return Some(());
                }
                let nested = matches!(x.kind, ExprKind::Array(_) | ExprKind::Repeat(..));
                let val = if nested { None } else { Some(self.expr(x)?) };
                let pre = self.cur.clone();
                let (lc, lb, le) = (self.new_label("rep.cond"), self.new_label("rep.body"), self.new_label("rep.end"));
                self.line(&format!("br label %{lc}"));
                self.start(&lc);
                let (i, i1, c) = (self.t(), self.t(), self.t());
                self.line(&format!("{i} = phi i64 [ 0, %{pre} ], [ {i1}, %{lb} ]"));
                self.line(&format!("{c} = icmp ult i64 {i}, {n}"));
                self.line(&format!("br i1 {c}, label %{lb}, label %{le}"));
                self.start(&lb);
                let slot = self.t();
                self.line(&format!("{slot} = getelementptr inbounds {at}, ptr {dest}, i64 0, i64 {i}"));
                match &val {
                    Some((v, t)) => self.line(&format!("store {} {v}, ptr {slot}", t.llty())),
                    None => {
                        self.init_array(&slot, x)?;
                    }
                }
                self.line(&format!("{i1} = add i64 {i}, 1"));
                self.line(&format!("br label %{lc}"));
                self.start(&le);
            }
            _ => unreachable!(),
        }
        Some(())
    }

    /// place 표현식의 (주소, 타입). 주소를 가질 수 없는 표현식이면 `None`.
    fn place(&mut self, e: &Expr) -> Option<(String, Ty)> {
        match &e.kind {
            ExprKind::Index(base, idx) => {
                let (data, len, elem) = self.seq_parts(base)?;
                let (iv, it) = self.expr(idx)?;
                let iv = self.widen(iv, it);
                let ok = self.t();
                self.line(&format!("{ok} = icmp ult i64 {iv}, {len}"));
                self.bounds_check(&ok);
                let t = self.t();
                self.line(&format!("{t} = getelementptr inbounds {}, ptr {data}, i64 {iv}", elem.llty()));
                Some((t, e.ty))
            }
            ExprKind::Var(n) => Some(self.lookup(n)),
            ExprKind::Deref(inner) => {
                let (p, _) = self.expr(inner)?;
                Some((p, e.ty))
            }
            ExprKind::Field(base, name) => {
                if matches!(base.ty, Ty::Str | Ty::String | Ty::Ref(Ty::Str | Ty::String, _)) {
                    let (ptr, agg) = match base.ty {
                        Ty::Ref(inner, _) => (self.expr(base)?.0, *inner),
                        t => {
                            let p = if base.is_place() {
                                self.place(base)?.0
                            } else {
                                self.spill(base)?
                            };
                            (p, t)
                        }
                    };
                    let idx = match name.as_str() {
                        "ptr" => 0,
                        _ => 1,
                    };
                    let t = self.t();
                    self.line(&format!(
                        "{t} = getelementptr inbounds {}, ptr {ptr}, i32 0, i32 {idx}",
                        agg.llty()
                    ));
                    return Some((t, e.ty));
                }
                let (bptr, sname) = match base.ty {
                    Ty::Ref(Ty::Struct(n), _) => (self.expr(base)?.0, *n),
                    Ty::Struct(n) => {
                        let ptr = if base.is_place() {
                            self.place(base)?.0
                        } else {
                            self.spill(base)?
                        };
                        (ptr, n)
                    }
                    _ => return None,
                };
                let idx = self.field_index(sname, name);
                let t = self.t();
                self.line(&format!(
                    "{t} = getelementptr inbounds %{}, ptr {bptr}, i32 0, i32 {idx}",
                    ll_quote(sname)
                ));
                Some((t, e.ty))
            }
            _ => None,
        }
    }

    /// `as` 변환. 실수 -> 정수는 범위를 넘으면 포화(saturate)하고 NaN은 0이 된다.
    fn cast(&mut self, v: String, from: Ty, to: Ty) -> Option<Val> {
        if from == to {
            return Some((v, to));
        }
        let t = self.t();
        let (f, tt) = (from.llty(), to.llty());
        if from.is_int() && to.is_int() {
            let (fb, tb) = (from.bits(), to.bits());
            if fb == tb {
                return Some((v, to)); // 같은 폭의 부호 변환은 비트 그대로
            }
            let inst = if tb < fb {
                "trunc"
            } else if from.is_signed() {
                "sext"
            } else {
                "zext"
            };
            self.line(&format!("{t} = {inst} {f} {v} to {tt}"));
        } else if from.is_int() && to == Ty::F64 {
            let inst = if from.is_signed() { "sitofp" } else { "uitofp" };
            self.line(&format!("{t} = {inst} {f} {v} to double"));
        } else if from == Ty::F64 && to.is_int() {
            let kind = if to.is_signed() { "fptosi" } else { "fptoui" };
            let name = format!("llvm.{kind}.sat.{tt}.f64");
            self.decls
                .insert(format!("declare {tt} @{name}(double)"));
            self.line(&format!("{t} = call {tt} @{name}(double {v})"));
        } else if matches!((from, to), (Ty::Ref(..) | Ty::Ptr(..), Ty::Ptr(..))) {
            return Some((v, to)); // 불투명 포인터라 비트 그대로
        } else if matches!(from, Ty::Ptr(..)) && to.is_int() {
            self.line(&format!("{t} = ptrtoint ptr {v} to {tt}"));
        } else if from.is_int() && matches!(to, Ty::Ptr(..)) {
            self.line(&format!("{t} = inttoptr {f} {v} to ptr"));
        } else if from == Ty::Bool && to.is_int() {
            self.line(&format!("{t} = zext i1 {v} to {tt}"));
        } else {
            return None;
        }
        Some((t, to))
    }

    fn block(&mut self, b: &Block) -> Option<Val> {
        self.push_scope();
        for s in &b.stmts {
            self.stmt(s);
        }
        let v = b.tail.as_ref().and_then(|e| self.expr(e));
        self.end_scope_drops();
        self.pop_scope();
        v
    }

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let {
                name,
                init,
                var_ty,
                ..
            } => {
                if matches!(init.kind, ExprKind::Array(_) | ExprKind::Repeat(..)) {
                    let ptr = self.declare(name, *var_ty);
                    if self.init_array(&ptr, init).is_some() {
                        self.set_live(&ptr, true);
                    }
                    return;
                }
                let v = self.expr(init);
                let ptr = self.declare(name, *var_ty);
                let has = v.is_some();
                let op = v.map(|x| x.0).unwrap_or_else(|| "undef".to_string());
                self.line(&format!("store {} {op}, ptr {ptr}", var_ty.llty()));
                if has {
                    self.set_live(&ptr, true);
                }
            }
            Stmt::Assign { target, value, .. } => {
                let v = self.expr(value);
                if let Some((ptr, ty)) = self.place(target) {
                    let heap = needs_drop(ty, self.structs);
                    let is_var = matches!(target.kind, ExprKind::Var(_));
                    // 이전 값을 먼저 해제한다. (변수는 이동되었을 수 있어 플래그를 본다.)
                    if heap && v.is_some() {
                        if is_var {
                            if let Some(flag) = self.flag_of.get(&ptr).cloned() {
                                self.drop_if_live(&ptr, &flag, ty);
                            }
                        } else {
                            self.call_drop(&ptr, ty);
                        }
                    }
                    let has = v.is_some();
                    let op = v.map(|x| x.0).unwrap_or_else(|| "undef".to_string());
                    self.line(&format!("store {} {op}, ptr {ptr}", ty.llty()));
                    if heap && is_var && has {
                        self.set_live(&ptr, true);
                    }
                }
            }
            Stmt::Return { value, .. } => {
                match value {
                    Some(e) => match self.expr(e) {
                        Some((v, t)) => {
                            self.drop_all_scopes();
                            self.line(&format!("ret {} {v}", t.llty()));
                        }
                        None => self.line("unreachable"),
                    },
                    None => {
                        self.drop_all_scopes();
                        self.line("ret void");
                    }
                }
                // return 뒤의 코드가 유효한 IR이 되도록 도달 불가능한 블록을 연다.
                let dead = self.new_label("dead");
                self.start(&dead);
            }
            Stmt::Break { .. } | Stmt::Continue { .. } => {
                if let Some((lcont, lbrk, depth)) = self.loops.last().cloned() {
                    self.drop_scopes_from(depth);
                    let target = if matches!(s, Stmt::Break { .. }) { lbrk } else { lcont };
                    self.line(&format!("br label %{target}"));
                }
                let dead = self.new_label("dead");
                self.start(&dead);
            }
            Stmt::While { cond, body, step, .. } => {
                let (lc, lb, le, ls) = (
                    self.new_label("while.cond"),
                    self.new_label("while.body"),
                    self.new_label("while.end"),
                    self.new_label("while.step"),
                );
                self.line(&format!("br label %{lc}"));
                self.start(&lc);
                let c = self
                    .expr(cond)
                    .map(|x| x.0)
                    .unwrap_or_else(|| "false".to_string());
                self.line(&format!("br i1 {c}, label %{lb}, label %{le}"));
                self.start(&lb);
                let depth = self.drops.len();
                self.loops.push((ls.clone(), le.clone(), depth));
                self.block(body);
                self.line(&format!("br label %{ls}"));
                self.start(&ls);
                for st in step {
                    self.stmt(st);
                }
                self.loops.pop();
                self.line(&format!("br label %{lc}"));
                self.start(&le);
            }
            Stmt::Expr(e) => {
                // 버려지는 임시값이 힙을 쥐고 있으면 바로 해제한다.
                if let Some((v, ty)) = self.expr(e) {
                    if needs_drop(ty, self.structs) {
                        self.tmp += 1;
                        let slot = format!("%tmpdrop.{}", self.tmp);
                        self.allocas.push_str(&format!("  {slot} = alloca {}\n", ty.llty()));
                        self.line(&format!("store {} {v}, ptr {slot}", ty.llty()));
                        self.call_drop(&slot, ty);
                    }
                }
            }
        }
    }

    fn expr(&mut self, e: &Expr) -> Option<Val> {
        match &e.kind {
            ExprKind::Int(n) => {
                // 64비트 부호 없는 상한 리터럴은 같은 비트 패턴의 부호 있는 수로 적는다.
                let v = if *n > i64::MAX as i128 { (*n as u64 as i64) as i128 } else { *n };
                Some((v.to_string(), e.ty))
            }
            // LLVM 호환을 위해 f64는 비트 패턴(16진)으로 내보낸다.
            ExprKind::Float(x) => Some((format!("0x{:016X}", x.to_bits()), Ty::F64)),
            ExprKind::Bool(b) => Some((b.to_string(), Ty::Bool)),
            ExprKind::Str(s) => {
                let g = format!("@.str.{}.{}", self.fi, self.nstr);
                self.nstr += 1;
                self.strs.push_str(&format!(
                    "{g} = private unnamed_addr constant [{} x i8] c\"{}\"\n",
                    s.len(),
                    ll_bytes(s)
                ));
                let a = self.t();
                self.line(&format!("{a} = insertvalue {{ ptr, i64 }} undef, ptr {g}, 0"));
                let b = self.t();
                self.line(&format!("{b} = insertvalue {{ ptr, i64 }} {a}, i64 {}, 1", s.len()));
                Some((b, Ty::Str))
            }
            ExprKind::NoneTag => Some(("zeroinitializer".to_string(), Ty::NoneTag)),
            ExprKind::Ctor(is_ok, arg) => {
                let (v, vt) = self.expr(arg)?;
                let rty = e.ty.llty();
                let a = self.t();
                self.line(&format!("{a} = insertvalue {rty} undef, i1 {}, 0", is_ok));
                let b = self.t();
                let idx = if *is_ok { 1 } else { 2 };
                self.line(&format!("{b} = insertvalue {rty} {a}, {} {v}, {idx}", vt.llty()));
                Some((b, e.ty))
            }
            ExprKind::Try(inner) => {
                let (v, rty) = self.expr(inner)?;
                let Ty::Result(_, err_ty) = rty else { return None };
                let tag = self.t();
                self.line(&format!("{tag} = extractvalue {} {v}, 0", rty.llty()));
                let (lo, le) = (self.new_label("try.ok"), self.new_label("try.err"));
                self.line(&format!("br i1 {tag}, label %{lo}, label %{le}"));
                self.start(&le);
                let ev = self.t();
                self.line(&format!("{ev} = extractvalue {} {v}, 2", rty.llty()));
                let ret = self.ret.llty();
                let a = self.t();
                self.line(&format!("{a} = insertvalue {ret} undef, i1 false, 0"));
                let b = self.t();
                self.line(&format!("{b} = insertvalue {ret} {a}, {} {ev}, 2", err_ty.llty()));
                self.drop_all_scopes();
                self.line(&format!("ret {ret} {b}"));
                self.start(&lo);
                let pv = self.t();
                self.line(&format!("{pv} = extractvalue {} {v}, 1", rty.llty()));
                Some((pv, e.ty))
            }
            ExprKind::Match { scrut, ok, err } => {
                let (v, rty) = self.expr(scrut)?;
                let tag = self.t();
                self.line(&format!("{tag} = extractvalue {} {v}, 0", rty.llty()));
                let (lo, le, lend) = (
                    self.new_label("match.ok"),
                    self.new_label("match.err"),
                    self.new_label("match.end"),
                );
                self.line(&format!("br i1 {tag}, label %{lo}, label %{le}"));
                let mut incoming = Vec::new();
                for (arm, lbl, idx) in [(ok, &lo, 1), (err, &le, 2)] {
                    self.start(lbl);
                    let pv = self.t();
                    self.line(&format!("{pv} = extractvalue {} {v}, {idx}", rty.llty()));
                    self.push_scope();
                    let slot = self.declare(&arm.bind, arm.bind_ty);
                    self.line(&format!("store {} {pv}, ptr {slot}", arm.bind_ty.llty()));
                    self.set_live(&slot, true);
                    let val = self.block(&arm.body);
                    self.end_scope_drops();
                    self.pop_scope();
                    let end = self.cur.clone();
                    self.line(&format!("br label %{lend}"));
                    incoming.push((val, end));
                }
                self.start(&lend);
                let ty = incoming.iter().find_map(|(v, _)| v.as_ref().map(|x| x.1))?;
                if ty == Ty::Unit || ty == Ty::Never {
                    return None;
                }
                let arms: Vec<String> = incoming
                    .iter()
                    .map(|(v, lbl)| {
                        let op = v.as_ref().map(|x| x.0.as_str()).unwrap_or("undef");
                        format!("[ {op}, %{lbl} ]")
                    })
                    .collect();
                let t = self.t();
                self.line(&format!("{t} = phi {} {}", ty.llty(), arms.join(", ")));
                Some((t, ty))
            }
            ExprKind::Array(_) | ExprKind::Repeat(..) => {
                self.tmp += 1;
                let tmp = format!("%arr.{}", self.tmp);
                self.allocas.push_str(&format!("  {tmp} = alloca {}\n", e.ty.llty()));
                self.init_array(&tmp, e)?;
                let t = self.t();
                self.line(&format!("{t} = load {}, ptr {tmp}", e.ty.llty()));
                Some((t, e.ty))
            }
            ExprKind::MethodCall(..) => unreachable!("typeck rewrites method calls into plain calls"),
            ExprKind::Slice(..) => unreachable!("typeck only allows a slice expression directly under `&`"),
            ExprKind::Field(base, name)
                if matches!(
                    base.ty,
                    Ty::Array(..) | Ty::Ref(Ty::Array(..) | Ty::Slice(_), _)
                ) =>
            {
                let (data, len, _) = self.seq_parts(base)?;
                if name == "len" {
                    Some((len, Ty::U64))
                } else {
                    Some((data, e.ty))
                }
            }
            ExprKind::Index(..) => {
                let (ptr, ty) = self.place(e)?;
                let t = self.t();
                self.line(&format!("{t} = load {}, ptr {ptr}", ty.llty()));
                Some((t, ty))
            }
            ExprKind::AddrOf(_, inner) if matches!(inner.kind, ExprKind::Slice(..)) => {
                let ExprKind::Slice(base, lo, hi) = &inner.kind else { unreachable!() };
                let (data, len, elem) = self.seq_parts(base)?;
                let lo_v = match lo {
                    Some(x) => {
                        let (v, t) = self.expr(x)?;
                        self.widen(v, t)
                    }
                    None => "0".to_string(),
                };
                let hi_v = match hi {
                    Some(x) => {
                        let (v, t) = self.expr(x)?;
                        self.widen(v, t)
                    }
                    None => len.clone(),
                };
                let (c1, c2, ok) = (self.t(), self.t(), self.t());
                self.line(&format!("{c1} = icmp ule i64 {lo_v}, {hi_v}"));
                self.line(&format!("{c2} = icmp ule i64 {hi_v}, {len}"));
                self.line(&format!("{ok} = and i1 {c1}, {c2}"));
                self.bounds_check(&ok);
                let (np, nl, f1, f2) = (self.t(), self.t(), self.t(), self.t());
                self.line(&format!("{np} = getelementptr inbounds {}, ptr {data}, i64 {lo_v}", elem.llty()));
                self.line(&format!("{nl} = sub i64 {hi_v}, {lo_v}"));
                self.line(&format!("{f1} = insertvalue {{ ptr, i64 }} undef, ptr {np}, 0"));
                self.line(&format!("{f2} = insertvalue {{ ptr, i64 }} {f1}, i64 {nl}, 1"));
                Some((f2, e.ty))
            }
            ExprKind::Field(..) => {
                let (ptr, ty) = self.place(e)?;
                let t = self.t();
                self.line(&format!("{t} = load {}, ptr {ptr}", ty.llty()));
                Some((t, ty))
            }
            ExprKind::AddrOf(_, inner) => {
                let (ptr, _) = self.place(inner)?;
                Some((ptr, e.ty))
            }
            ExprKind::Deref(inner) => {
                let (p, _) = self.expr(inner)?;
                let t = self.t();
                self.line(&format!("{t} = load {}, ptr {p}", e.ty.llty()));
                Some((t, e.ty))
            }
            ExprKind::StructLit(name, inits) => {
                let sty = e.ty;
                let mut vals = Vec::new();
                for init in inits {
                    let (v, ty) = self.expr(&init.value)?;
                    vals.push((self.field_index(name, &init.name), v, ty));
                }
                let mut cur = "undef".to_string();
                for (idx, v, ty) in vals {
                    let t = self.t();
                    self.line(&format!(
                        "{t} = insertvalue {} {cur}, {} {v}, {idx}",
                        sty.llty(),
                        ty.llty()
                    ));
                    cur = t;
                }
                Some((cur, sty))
            }
            ExprKind::Cast(inner, _) => {
                let (v, from) = self.expr(inner)?;
                let to = e.ty;
                self.cast(v, from, to)
            }
            ExprKind::TypedInt(..) | ExprKind::RepeatOf(..) | ExprKind::Generic(..) => unreachable!("resolved before codegen"),
            ExprKind::Var(name) => {
                let (ptr, ty) = self.lookup(name);
                let t = self.t();
                self.line(&format!("{t} = load {}, ptr {ptr}", ty.llty()));
                // 값으로 쓰면 이동이다: 스코프 끝에서 더는 해제하지 않는다.
                self.set_live(&ptr, false);
                Some((t, ty))
            }
            ExprKind::Unary(UnOp::Neg, inner) if matches!(inner.kind, ExprKind::Int(_)) && inner.ty.is_int() => {
                // 음수 리터럴은 그대로 적는다. (`-128`의 `128`은 i8에 안 들어가 부정 연산이 넘친다.)
                let ExprKind::Int(n) = inner.kind else { unreachable!() };
                Some(((-n).to_string(), inner.ty))
            }
            ExprKind::Unary(op, inner) => {
                let (v, vt) = self.expr(inner)?;
                let t = self.t();
                match op {
                    UnOp::Neg if vt == Ty::F64 => {
                        self.line(&format!("{t} = fneg double {v}"));
                        Some((t, Ty::F64))
                    }
                    UnOp::Neg if vt.is_int() => {
                        let r = self.checked_arith("sub", vt, "0", &v);
                        Some((r, vt))
                    }
                    UnOp::Neg => {
                        self.line(&format!("{t} = sub {} 0, {v}", vt.llty()));
                        Some((t, vt))
                    }
                    UnOp::BitNot => {
                        self.line(&format!("{t} = xor {} {v}, -1", vt.llty()));
                        Some((t, vt))
                    }
                    UnOp::Not => {
                        self.line(&format!("{t} = xor i1 {v}, true"));
                        Some((t, Ty::Bool))
                    }
                }
            }
            ExprKind::Binary(op @ (BinOp::And | BinOp::Or), l, r) => {
                let (lv, _) = self.expr(l)?;
                let lhs_end = self.cur.clone();
                let (lr, le) = (self.new_label("sc.rhs"), self.new_label("sc.end"));
                if *op == BinOp::And {
                    self.line(&format!("br i1 {lv}, label %{lr}, label %{le}"));
                } else {
                    self.line(&format!("br i1 {lv}, label %{le}, label %{lr}"));
                }
                self.start(&lr);
                let rv = self
                    .expr(r)
                    .map(|x| x.0)
                    .unwrap_or_else(|| "undef".to_string());
                let rhs_end = self.cur.clone();
                self.line(&format!("br label %{le}"));
                self.start(&le);
                let short = if *op == BinOp::And { "false" } else { "true" };
                let t = self.t();
                self.line(&format!(
                    "{t} = phi i1 [ {short}, %{lhs_end} ], [ {rv}, %{rhs_end} ]"
                ));
                Some((t, Ty::Bool))
            }
            ExprKind::Binary(op, l, r) => {
                let (lv, lt) = self.expr(l)?;
                let (rv, rt) = self.expr(r)?;
                if let (Ty::Ptr(elem, _), BinOp::Add | BinOp::Sub) = (lt, op) {
                    // 포인터 산술: 원소 크기 단위로 이동한다.
                    let mut idx = rv;
                    if rt.bits() < 64 {
                        let w = self.t();
                        let inst = if rt.is_signed() { "sext" } else { "zext" };
                        self.line(&format!("{w} = {inst} {} {idx} to i64", rt.llty()));
                        idx = w;
                    }
                    if *op == BinOp::Sub {
                        let n = self.t();
                        self.line(&format!("{n} = sub i64 0, {idx}"));
                        idx = n;
                    }
                    let t = self.t();
                    self.line(&format!("{t} = getelementptr {}, ptr {lv}, i64 {idx}", elem.llty()));
                    return Some((t, lt));
                }
                use BinOp::*;
                if lt == Ty::Str && matches!(op, Eq | Ne) {
                    self.decls.insert(STREQ_DEF.to_string());
                    let (la, lb, ra, rb) = (self.t(), self.t(), self.t(), self.t());
                    self.line(&format!("{la} = extractvalue {{ ptr, i64 }} {lv}, 0"));
                    self.line(&format!("{lb} = extractvalue {{ ptr, i64 }} {lv}, 1"));
                    self.line(&format!("{ra} = extractvalue {{ ptr, i64 }} {rv}, 0"));
                    self.line(&format!("{rb} = extractvalue {{ ptr, i64 }} {rv}, 1"));
                    let eq = self.t();
                    self.line(&format!("{eq} = call i1 @tam_streq(ptr {la}, i64 {lb}, ptr {ra}, i64 {rb})"));
                    if *op == Ne {
                        let n = self.t();
                        self.line(&format!("{n} = xor i1 {eq}, true"));
                        return Some((n, Ty::Bool));
                    }
                    return Some((eq, Ty::Bool));
                }
                if lt.is_int() && matches!(op, Add | Sub | Mul) {
                    let name = match op {
                        Add => "add",
                        Sub => "sub",
                        _ => "mul",
                    };
                    let v = self.checked_arith(name, lt, &lv, &rv);
                    return Some((v, lt));
                }
                if lt.is_int() && matches!(op, Div | Rem) {
                    let z = self.t();
                    self.line(&format!("{z} = icmp eq {} {rv}, 0", lt.llty()));
                    self.trap_if(&z, "division by zero");
                    if lt.is_signed() {
                        let min = -(1i128 << (lt.bits() - 1));
                        let (a, b, both) = (self.t(), self.t(), self.t());
                        self.line(&format!("{a} = icmp eq {} {lv}, {min}", lt.llty()));
                        self.line(&format!("{b} = icmp eq {} {rv}, -1", lt.llty()));
                        self.line(&format!("{both} = and i1 {a}, {b}"));
                        self.trap_if(&both, "integer overflow in division");
                    }
                }
                let t = self.t();
                let float = lt == Ty::F64;
                let sg = lt.is_signed();
                let (inst, res) = match op {
                    Add => (if float { "fadd" } else { "add" }, lt),
                    Sub => (if float { "fsub" } else { "sub" }, lt),
                    Mul => (if float { "fmul" } else { "mul" }, lt),
                    WrapAdd => ("add", lt),
                    WrapSub => ("sub", lt),
                    WrapMul => ("mul", lt),
                    Div => (
                        if float {
                            "fdiv"
                        } else if sg {
                            "sdiv"
                        } else {
                            "udiv"
                        },
                        lt,
                    ),
                    Rem => (
                        if float {
                            "frem"
                        } else if sg {
                            "srem"
                        } else {
                            "urem"
                        },
                        lt,
                    ),
                    Eq => (if float { "fcmp oeq" } else { "icmp eq" }, Ty::Bool),
                    Ne => (if float { "fcmp une" } else { "icmp ne" }, Ty::Bool),
                    Lt => (
                        if float {
                            "fcmp olt"
                        } else if sg {
                            "icmp slt"
                        } else {
                            "icmp ult"
                        },
                        Ty::Bool,
                    ),
                    Le => (
                        if float {
                            "fcmp ole"
                        } else if sg {
                            "icmp sle"
                        } else {
                            "icmp ule"
                        },
                        Ty::Bool,
                    ),
                    Gt => (
                        if float {
                            "fcmp ogt"
                        } else if sg {
                            "icmp sgt"
                        } else {
                            "icmp ugt"
                        },
                        Ty::Bool,
                    ),
                    Ge => (
                        if float {
                            "fcmp oge"
                        } else if sg {
                            "icmp sge"
                        } else {
                            "icmp uge"
                        },
                        Ty::Bool,
                    ),
                    BitAnd => ("and", lt),
                    BitOr => ("or", lt),
                    BitXor => ("xor", lt),
                    Shl | Shr => {
                        // 시프트 양을 왼쪽 피연산자 폭으로 맞추고 폭-1로 마스크한다(범위를 넘는 시프트가 poison이 되지 않게).
                        let mut amt = rv.clone();
                        if rt.bits() < lt.bits() {
                            let w = self.t();
                            let inst = if rt.is_signed() { "sext" } else { "zext" };
                            self.line(&format!("{w} = {inst} {} {amt} to {}", rt.llty(), lt.llty()));
                            amt = w;
                        } else if rt.bits() > lt.bits() {
                            let w = self.t();
                            self.line(&format!("{w} = trunc {} {amt} to {}", rt.llty(), lt.llty()));
                            amt = w;
                        }
                        let m = self.t();
                        self.line(&format!("{m} = and {} {amt}, {}", lt.llty(), lt.bits() - 1));
                        let inst = match op {
                            Shl => "shl",
                            _ if sg => "ashr",
                            _ => "lshr",
                        };
                        self.line(&format!("{t} = {inst} {} {lv}, {m}", lt.llty()));
                        return Some((t, lt));
                    }
                    And | Or => unreachable!(),
                };
                self.line(&format!("{t} = {inst} {} {lv}, {rv}", lt.llty()));
                Some((t, res))
            }
            ExprKind::Call(name, args) if is_builtin(name) => self.builtin(name, args),
            ExprKind::Call(name, args) => {
                let (_, ret) = self.sigs[name].clone();
                let ext = self.ext_syms.get(name.as_str()).cloned();
                let mut ops = Vec::new();
                for a in args {
                    let (v, ty) = self.expr(a)?;
                    let attr = if ext.is_some() { abi_attr(ty) } else { "" };
                    ops.push(format!("{}{attr} {v}", ty.llty()));
                }
                let sym = ll_quote(ext.as_deref().unwrap_or(name));
                if ret == Ty::Unit {
                    self.line(&format!("call void @{sym}({})", ops.join(", ")));
                    None
                } else {
                    let t = self.t();
                    let ra = if ext.is_some() { abi_attr_prefix(ret) } else { "" };
                    self.line(&format!("{t} = call {ra}{} @{sym}({})", ret.llty(), ops.join(", ")));
                    Some((t, ret))
                }
            }
            ExprKind::Unsafe(b) => self.block(b),
            ExprKind::If { cond, then, els } => {
                let (c, _) = self.expr(cond)?;
                let (lt, le, lend) = (
                    self.new_label("if.then"),
                    self.new_label("if.else"),
                    self.new_label("if.end"),
                );
                let else_target = if els.is_some() { &le } else { &lend };
                self.line(&format!("br i1 {c}, label %{lt}, label %{else_target}"));
                self.start(&lt);
                let tv = self.block(then);
                let then_end = self.cur.clone();
                self.line(&format!("br label %{lend}"));
                let mut incoming = vec![(tv, then_end)];
                if let Some(eb) = els {
                    self.start(&le);
                    let ev = self.block(eb);
                    let else_end = self.cur.clone();
                    self.line(&format!("br label %{lend}"));
                    incoming.push((ev, else_end));
                }
                self.start(&lend);
                if els.is_none() {
                    return None;
                }
                let ty = incoming.iter().find_map(|(v, _)| v.as_ref().map(|x| x.1))?;
                if ty == Ty::Unit || ty == Ty::Never {
                    return None;
                }
                let arms: Vec<String> = incoming
                    .iter()
                    .map(|(v, lbl)| {
                        let op = v.as_ref().map(|x| x.0.as_str()).unwrap_or("undef");
                        format!("[ {op}, %{lbl} ]")
                    })
                    .collect();
                let t = self.t();
                self.line(&format!("{t} = phi {} {}", ty.llty(), arms.join(", ")));
                Some((t, ty))
            }
        }
    }
}

/// `str == str`용 바이트 비교 (런타임 라이브러리 없이 쓰려고 IR로 직접 쓴다).
/// 호스트용 패닉: `tam: panic: <msg>\n`을 stderr(fd 2)에 쓰고 trap한다.
/// libc 없이 쓰려고 리눅스 `write` 시스콜을 직접 호출한다.
#[cfg(target_arch = "aarch64")]
const SYS_WRITE: &str = "  %r = call i64 asm sideeffect \"svc #0\", \"={x0},{x8},{x0},{x1},{x2},~{memory}\"(i64 64, i64 2, ptr %p, i64 %n)\n";
#[cfg(not(target_arch = "aarch64"))]
const SYS_WRITE: &str = "  %r = call i64 asm sideeffect \"syscall\", \"={rax},{rax},{rdi},{rsi},{rdx},~{rcx},~{r11},~{memory}\"(i64 1, i64 2, ptr %p, i64 %n)\n";

fn panic_def() -> String {
    format!(
        "@.tam.pre = private unnamed_addr constant [12 x i8] c\"tam: panic: \"\n\
@.tam.nl = private unnamed_addr constant [1 x i8] c\"\\0A\"\n\
define internal void @tam_write2(ptr %p, i64 %n) {{\n{SYS_WRITE}  ret void\n}}\n\
define internal void @tam_panic(ptr %p, i64 %n) {{\n\
  call void @tam_write2(ptr @.tam.pre, i64 12)\n\
  call void @tam_write2(ptr %p, i64 %n)\n\
  call void @tam_write2(ptr @.tam.nl, i64 1)\n\
  call void @llvm.trap()\n\
  unreachable\n}}"
    )
}

const STREQ_DEF: &str = "\
define internal i1 @tam_streq(ptr %a, i64 %al, ptr %b, i64 %bl) {
  %same = icmp eq i64 %al, %bl
  br i1 %same, label %loop, label %no
loop:
  %i = phi i64 [ 0, %0 ], [ %n, %step ]
  %done = icmp eq i64 %i, %al
  br i1 %done, label %yes, label %cmp
cmp:
  %pa = getelementptr inbounds i8, ptr %a, i64 %i
  %pb = getelementptr inbounds i8, ptr %b, i64 %i
  %ca = load i8, ptr %pa
  %cb = load i8, ptr %pb
  %e = icmp eq i8 %ca, %cb
  br i1 %e, label %step, label %no
step:
  %n = add i64 %i, 1
  br label %loop
yes:
  ret i1 true
no:
  ret i1 false
}";

